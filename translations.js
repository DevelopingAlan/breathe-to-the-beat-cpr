function normalizeTranslationKey(value) {
  return value
    .replace(/\u00e2\u20ac\u201d/g, "—")
    .replace(/\u00e2\u20ac\u201c/g, "–")
    .replace(/\u00e2\u20ac\u2122/g, "’")
    .replace(/\u00e2\u20ac\u0153/g, "“")
    .replace(/\u00e2\u20ac\u009d/g, "”")
    .replace(/\s+/g, " ")
    .trim();
}

const originalTextNodes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);

while (textWalker.nextNode()) {
  const node = textWalker.currentNode;
  const parent = node.parentElement;

  if (!parent || parent.closest("script, style, noscript")) {
    continue;
  }

  if (node.nodeValue.trim()) {
    originalTextNodes.push({ node, value: node.nodeValue });
  }
}

const translatedAttributes = [];
const translatableAttributes = ["alt", "aria-label", "placeholder", "title"];

document.querySelectorAll("*").forEach((element) => {
  translatableAttributes.forEach((attribute) => {
    if (element.hasAttribute(attribute)) {
      translatedAttributes.push({
        element,
        attribute,
        value: element.getAttribute(attribute),
      });
    }
  });
});

const originalTitle = document.title;
const descriptionMeta = document.querySelector('meta[name="description"]');
const originalDescription = descriptionMeta?.content || "";
let siteLanguage = "en";

function getLocalizedText(text) {
  return siteLanguage === "es"
    ? spanishTranslations[normalizeTranslationKey(text)] || text
    : text;
}

function renderTextNode({ node, value }) {
  if (siteLanguage === "en") {
    node.nodeValue = value;
    return;
  }

  const leadingWhitespace = value.match(/^\s*/)[0];
  const trailingWhitespace = value.match(/\s*$/)[0];
  const text = value.slice(
    leadingWhitespace.length,
    value.length - trailingWhitespace.length
  );
  const translation = spanishTranslations[normalizeTranslationKey(text)];
  node.nodeValue = translation
    ? `${leadingWhitespace}${translation}${trailingWhitespace}`
    : value;
}

function applyLanguage(language) {
  siteLanguage = language === "es" ? "es" : "en";
  window.siteLanguage = siteLanguage;
  window.getLocalizedText = getLocalizedText;
  document.documentElement.lang = siteLanguage;
  document.title =
    siteLanguage === "es"
      ? "Breathe to the Beat Community CPR | Cursos de RCP comunitaria"
      : originalTitle;

  originalTextNodes.forEach(renderTextNode);
  translatedAttributes.forEach(({ element, attribute, value }) => {
    element.setAttribute(attribute, getLocalizedText(value));
  });

  const menuToggle = document.querySelector("#mobileMenuToggle");
  if (menuToggle) {
    const menuIsExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute(
      "aria-label",
      getLocalizedText(
        menuIsExpanded ? "Close navigation menu" : "Open navigation menu"
      )
    );
  }

  if (descriptionMeta) {
    descriptionMeta.content =
      siteLanguage === "es"
        ? "Capacitación comunitaria, práctica y accesible en RCP, primeros auxilios y DEA en Somerville, Massachusetts."
        : originalDescription;
  }

  document.querySelectorAll("[data-language-selector]").forEach((selector) => {
    selector.value = siteLanguage;
  });

  document.querySelectorAll("[data-form-status][data-message]").forEach((status) => {
    status.textContent = getLocalizedText(status.dataset.message);
    if (siteLanguage === "en" && status.dataset.messageDetail) {
      status.textContent += ` ${status.dataset.messageDetail}`;
    }
  });

  document
    .querySelectorAll('form[data-submitting="true"] button[type="submit"]')
    .forEach((button) => {
      button.textContent = getLocalizedText("Sending...");
    });

  document.dispatchEvent(
    new CustomEvent("site-language-change", {
      detail: { language: siteLanguage },
    })
  );
}

document.querySelectorAll("[data-language-selector]").forEach((selector) => {
  selector.addEventListener("change", () => applyLanguage(selector.value));
});

window.siteLanguage = siteLanguage;
window.getLocalizedText = getLocalizedText;
